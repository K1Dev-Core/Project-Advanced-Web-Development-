export const toJob = (source: Plan): Job => {
  const deliveryRoute = source.routes[0];
  return {
    geometry: deliveryRoute.geometry,
    jobCode: deliveryRoute.jobCode,
    color: deliveryRoute.color,
    colorName: deliveryRoute.colorName,
    planStatus: source.status,
    deliveryDate: source.deliveryDate,
    status: deliveryRoute.status,
    rider: deliveryRoute.rider,
    shop: source.shop,
    departureTime: source.departureTime,
    deadlineTime: source.deadlineTime,
    finishTime: deliveryRoute.finishTime,
    totalOrders: deliveryRoute.orderCount,
    totalBoxes: deliveryRoute.boxCount,
    distanceKm: deliveryRoute.distanceKm,
    durationMinutes: deliveryRoute.durationMinutes,
    riderFee: deliveryRoute.riderFee,
    deliveredStops: 0,
    remainingStops: deliveryRoute.stops.length,
    navigationUrl: deliveryRoute.navigationUrl,
    path: deliveryRoute.path,
    stops: deliveryRoute.stops,
  };
};
